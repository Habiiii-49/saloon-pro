 */
require_once __DIR__ . '/../../includes/functions.php';
require_once __DIR__ . '/../../includes/finance.php';

requireRole('admin');

$pageTitle = 'Receipts';
$activeMenu = 'receipts';
$extraCss   = 'admin/payments/assets/css/payments.css';

$db    = getDBConnection();
$search = trim($_GET['search'] ?? '');

$sql = "
    SELECT r.receipt_id, r.receipt_number, r.created_at, r.generated_by,
           p.payment_id, p.amount, p.refunded_amount, p.payment_method, p.paid_at, p.transaction_ref,
           i.invoice_id, i.invoice_number,
           CONCAT(c.first_name,' ',c.last_name) AS client_name,
           CONCAT(u.first_name,' ',u.last_name) AS generated_by_name
    FROM receipts r
    JOIN payments p ON p.payment_id = r.payment_id
    LEFT JOIN invoices i ON i.invoice_id = p.invoice_id
    LEFT JOIN clients c ON c.client_id = COALESCE(p.client_id, i.client_id)
    LEFT JOIN users u ON u.user_id = r.generated_by
";
$params = [];
if ($search !== '') {
    $sql .= " WHERE r.receipt_number LIKE :s1 OR i.invoice_number LIKE :s2 OR CONCAT(c.first_name,' ',c.last_name) LIKE :s3";
    $params[':s1'] = '%' . $search . '%';
    $params[':s2'] = '%' . $search . '%';
    $params[':s3'] = '%' . $search . '%';
}
$sql .= " ORDER BY r.receipt_id DESC LIMIT 300";

$stmt = $db->prepare($sql);
$stmt->execute($params);
$receipts = $stmt->fetchAll();
?>
