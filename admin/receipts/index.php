        <form method="get" class="d-flex gap-2">
            <div class="filter-search">
                <i class="fas fa-magnifying-glass"></i>
                <input type="text" name="search" value="<?php echo sanitize($search); ?>" placeholder="Receipt, invoice or client…" class="form-control-admin form-control-sm">
            </div>
            <button class="btn-admin btn-cyan btn-xs"><i class="fas fa-filter"></i> Filter</button>
            <?php if ($search !== ''): ?><a href="<?php echo SITE_URL; ?>/admin/receipts/index.php" class="btn-admin btn-outline btn-xs">Clear</a><?php endif; ?>
        </form>
    </div>

    <?php if (!$receipts): ?>
    <div class="empty-state"><i class="fas fa-receipt"></i><h5>No receipts yet</h5><p>Receipts are issued automatically when a payment is collected.</p></div>
    <?php else: ?>
    <div class="table-scroll">
        <table class="admin-table">
            <thead>
                <tr>
                    <th>Receipt</th>
                    <th>Issued</th>
                    <th>Invoice</th>
                    <th>Client</th>
                    <th>Method</th>
                    <th class="fin-amount">Amount</th>
                    <th>Payment</th>
                    <th>Generated By</th>
                    <th>Actions</th>
                </tr>
            </thead>
            <tbody>
                <?php foreach ($receipts as $r): ?>
                <tr>
                    <td><strong><?php echo sanitize($r['receipt_number']); ?></strong></td>
                    <td><?php echo formatDate($r['created_at'], 'M d, Y g:i A'); ?></td>
                    <td>
                        <?php if ($r['invoice_number']): ?><a class="text-cyan-link" href="<?php echo SITE_URL; ?>/admin/invoices/view.php?id=<?php echo (int)$r['invoice_id']; ?>"><?php echo sanitize($r['invoice_number']); ?></a><?php else: ?>—<?php endif; ?>
                    </td>
                    <td><?php echo sanitize($r['client_name'] ?? '—'); ?></td>
                    <td><?php echo sanitize(ucfirst(str_replace('_', ' ', $r['payment_method']))); ?></td>
