                    <td><a class="text-cyan-link" href="<?php echo SITE_URL; ?>/admin/payments/view.php?id=<?php echo (int)$r['payment_id']; ?>">#<?php echo (int)$r['payment_id']; ?></a></td>
                    <td><?php echo $r['generated_by_name'] ? sanitize($r['generated_by_name']) : '—'; ?></td>
                    <td><a class="btn-admin btn-outline btn-xs" target="_blank" href="<?php echo SITE_URL; ?>/admin/receipts/print.php?receipt_id=<?php echo (int)$r['receipt_id']; ?>" title="Print"><i class="fas fa-print"></i></a></td>
                </tr>
                <?php endforeach; ?>
            </tbody>
        </table>
    </div>
    <?php endif; ?>
